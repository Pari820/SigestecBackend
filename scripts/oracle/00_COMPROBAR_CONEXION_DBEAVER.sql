-- Ejecutar en DBeaver conectado como SIGESTEC_ADS a FREEPDB1.
-- Solo consultas: no crea, altera ni elimina objetos.
SELECT USER AS usuario_oracle,
       SYS_CONTEXT('USERENV', 'SERVICE_NAME') AS servicio,
       SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS esquema
FROM dual;

SELECT COUNT(*) AS tablas_actuales FROM user_tables;

SELECT table_name FROM user_tables ORDER BY table_name;

-- Las entidades JPA de SIGESTEC mapean 36 tablas (no necesariamente las 45 del ADS completo).
SELECT COUNT(*) AS tablas_mapeadas_presentes
FROM user_tables
WHERE table_name IN (
  'PERFIL','PERSONA_NATURAL','PERSONA_JURIDICA','CARGO','EMPLEADO',
  'TECNICO','REPRESENTANTE_EMPRESA','TIPO_SERVICIO','USUARIO','ROL',
  'USUARIO_ROL','SOLICITUD_SERVICIO','COTIZACION','DETALLE_COTIZACION',
  'ORDEN_COMPRA','DETALLE_ORDEN_COMPRA','ORDEN_TRABAJO','ASIGNACION_PERSONAL',
  'DOCUMENTO_PLANIFICACION','ANALISIS_TRABAJO_SEGURO','RIESGO',
  'DETALLE_ANALISIS_RIESGO','EQUIPO_PROTECCION_PERSONAL',
  'ANALISIS_EQUIPO_PROTECCION_PERSONAL','HERRAMIENTA_EQUIPO',
  'ANALISIS_HERRAMIENTA_EQUIPO','APROBACION_ATS','EJECUCION_SERVICIO',
  'EVIDENCIA_EJECUCION','MATERIAL','MATERIAL_UTILIZADO','INFORME_TECNICO',
  'EVIDENCIA_INFORME_TECNICO','CONFORMIDAD_SERVICIO',
  'MOVIMIENTO_MATERIAL_ALMACEN','MOVIMIENTO_HERRAMIENTA_EQUIPO'
);
