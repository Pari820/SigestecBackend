-- SIGESTEC - Numeracion correlativa de documentos y catalogos
-- Ejecutar UNA SOLA VEZ como propietario del esquema SIGESTEC_ADS, despues de
-- crear las tablas base (01), la extension CU07-CU12 (04) y las tablas de almacen.
--
-- IMPORTANTE:
--   * Reorganiza codigos visibles de datos de PRUEBA por fecha y luego ID interno.
--   * NO modifica claves primarias ni claves foraneas.
--   * En ORDEN_COMPRA conserva NUMERO_ORDEN_COMPRA (documento externo del cliente)
--     y agrega CODIGO_INTERNO como referencia correlativa de SIGESTEC.
--   * Los nuevos correlativos se reservan dentro de la transaccion de registro.
--   * Respaldar la BD antes de ejecutar. No usar para renumerar informacion real.

DECLARE
    PROCEDURE agregar_columna_si_falta(p_tabla VARCHAR2, p_columna VARCHAR2, p_tipo VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(p_tabla) AND COLUMN_NAME = UPPER(p_columna);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || DBMS_ASSERT.SIMPLE_SQL_NAME(UPPER(p_tabla)) ||
                              ' ADD (' || DBMS_ASSERT.SIMPLE_SQL_NAME(UPPER(p_columna)) || ' ' || p_tipo || ')';
        END IF;
    END;
BEGIN
    agregar_columna_si_falta('SOLICITUD_SERVICIO', 'CODIGO_SOLICITUD', 'VARCHAR2(30)');
    agregar_columna_si_falta('ORDEN_COMPRA', 'CODIGO_INTERNO', 'VARCHAR2(30)');
    agregar_columna_si_falta('ANALISIS_TRABAJO_SEGURO', 'NUMERO_ATS', 'VARCHAR2(30)');
    agregar_columna_si_falta('EJECUCION_SERVICIO', 'NUMERO_EJECUCION', 'VARCHAR2(30)');
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'CORRELATIVO_DOCUMENTO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE CORRELATIVO_DOCUMENTO (
                TIPO_DOCUMENTO VARCHAR2(30) NOT NULL,
                ANIO NUMBER(4) NOT NULL,
                ULTIMO_NUMERO NUMBER(10) DEFAULT 0 NOT NULL,
                CONSTRAINT PK_CORRELATIVO_DOCUMENTO PRIMARY KEY (TIPO_DOCUMENTO, ANIO),
                CONSTRAINT CK_CORRELATIVO_ULTIMO CHECK (ULTIMO_NUMERO >= 0)
            )';
    END IF;
END;
