-- Renumerar solicitudes por fecha de recepcion.
MERGE INTO SOLICITUD_SERVICIO destino
USING (
    SELECT ID_SOLICITUD,
           'SOL-' || TO_CHAR(FECHA_SOLICITUD, 'YYYY') || '-' ||
           LPAD(TO_CHAR(ROW_NUMBER() OVER (
               PARTITION BY TO_CHAR(FECHA_SOLICITUD, 'YYYY') ORDER BY FECHA_SOLICITUD, ID_SOLICITUD
           )), 3, '0') AS NUEVO_CODIGO
      FROM SOLICITUD_SERVICIO
) origen
ON (destino.ID_SOLICITUD = origen.ID_SOLICITUD)
WHEN MATCHED THEN UPDATE SET destino.CODIGO_SOLICITUD = origen.NUEVO_CODIGO;

-- Renumerar cotizaciones por fecha de emision.
MERGE INTO COTIZACION destino
USING (
    SELECT ID_COTIZACION,
           'COT-' || TO_CHAR(FECHA_EMISION, 'YYYY') || '-' ||
           LPAD(TO_CHAR(ROW_NUMBER() OVER (
               PARTITION BY TO_CHAR(FECHA_EMISION, 'YYYY') ORDER BY FECHA_EMISION, ID_COTIZACION
           )), 3, '0') AS NUEVO_CODIGO
      FROM COTIZACION
) origen
ON (destino.ID_COTIZACION = origen.ID_COTIZACION)
WHEN MATCHED THEN UPDATE SET destino.NUMERO_COTIZACION = origen.NUEVO_CODIGO;

-- Codigo interno de OC; se conserva intacto el numero externo del documento.
MERGE INTO ORDEN_COMPRA destino
USING (
    SELECT ID_ORDEN_COMPRA,
           'OC-' || TO_CHAR(FECHA_EMISION, 'YYYY') || '-' ||
           LPAD(TO_CHAR(ROW_NUMBER() OVER (
               PARTITION BY TO_CHAR(FECHA_EMISION, 'YYYY') ORDER BY FECHA_EMISION, ID_ORDEN_COMPRA
           )), 3, '0') AS NUEVO_CODIGO
      FROM ORDEN_COMPRA
) origen
ON (destino.ID_ORDEN_COMPRA = origen.ID_ORDEN_COMPRA)
WHEN MATCHED THEN UPDATE SET destino.CODIGO_INTERNO = origen.NUEVO_CODIGO;

-- OT: no tiene fecha propia de creacion; se usa fecha de emision de su OC y el ID interno como desempate.
MERGE INTO ORDEN_TRABAJO destino
USING (
    SELECT ot.ID_ORDEN_TRABAJO,
           'OT-' || TO_CHAR(EXTRACT(YEAR FROM NVL(oc.FECHA_EMISION, SYSDATE))) || '-' ||
           LPAD(TO_CHAR(ROW_NUMBER() OVER (
               PARTITION BY EXTRACT(YEAR FROM NVL(oc.FECHA_EMISION, SYSDATE)) ORDER BY ot.ID_ORDEN_TRABAJO
           )), 3, '0') AS NUEVO_CODIGO
      FROM ORDEN_TRABAJO ot
      JOIN ORDEN_COMPRA oc ON oc.ID_ORDEN_COMPRA = ot.ID_ORDEN_COMPRA
) origen
ON (destino.ID_ORDEN_TRABAJO = origen.ID_ORDEN_TRABAJO)
WHEN MATCHED THEN UPDATE SET destino.NUMERO_ORDEN_TRABAJO = origen.NUEVO_CODIGO;

MERGE INTO ANALISIS_TRABAJO_SEGURO destino
USING (
    SELECT ID_ANALISIS_TRABAJO_SEGURO,
           'ATS-' || TO_CHAR(FECHA_REGISTRO, 'YYYY') || '-' ||
           LPAD(TO_CHAR(ROW_NUMBER() OVER (
               PARTITION BY TO_CHAR(FECHA_REGISTRO, 'YYYY') ORDER BY FECHA_REGISTRO, ID_ANALISIS_TRABAJO_SEGURO
           )), 3, '0') AS NUEVO_CODIGO
      FROM ANALISIS_TRABAJO_SEGURO
) origen
ON (destino.ID_ANALISIS_TRABAJO_SEGURO = origen.ID_ANALISIS_TRABAJO_SEGURO)
WHEN MATCHED THEN UPDATE SET destino.NUMERO_ATS = origen.NUEVO_CODIGO;

MERGE INTO EJECUCION_SERVICIO destino
USING (
    SELECT ID_EJECUCION_SERVICIO,
           'EJE-' || TO_CHAR(EXTRACT(YEAR FROM FECHA_EJECUCION)) || '-' ||
           LPAD(TO_CHAR(ROW_NUMBER() OVER (
               PARTITION BY EXTRACT(YEAR FROM FECHA_EJECUCION) ORDER BY FECHA_EJECUCION, ID_EJECUCION_SERVICIO
           )), 3, '0') AS NUEVO_CODIGO
      FROM EJECUCION_SERVICIO
) origen
ON (destino.ID_EJECUCION_SERVICIO = origen.ID_EJECUCION_SERVICIO)
WHEN MATCHED THEN UPDATE SET destino.NUMERO_EJECUCION = origen.NUEVO_CODIGO;

MERGE INTO INFORME_TECNICO destino
USING (
    SELECT ID_INFORME_TECNICO,
           'INF-' || TO_CHAR(FECHA_INFORME, 'YYYY') || '-' ||
           LPAD(TO_CHAR(ROW_NUMBER() OVER (
               PARTITION BY TO_CHAR(FECHA_INFORME, 'YYYY') ORDER BY FECHA_INFORME, ID_INFORME_TECNICO
           )), 3, '0') AS NUEVO_CODIGO
      FROM INFORME_TECNICO
) origen
ON (destino.ID_INFORME_TECNICO = origen.ID_INFORME_TECNICO)
WHEN MATCHED THEN UPDATE SET destino.NUMERO_INFORME = origen.NUEVO_CODIGO;

MERGE INTO MATERIAL destino
USING (
    SELECT ID_MATERIAL, 'MAT-' || LPAD(TO_CHAR(ROW_NUMBER() OVER (ORDER BY ID_MATERIAL)), 6, '0') AS NUEVO_CODIGO
      FROM MATERIAL
) origen
ON (destino.ID_MATERIAL = origen.ID_MATERIAL)
WHEN MATCHED THEN UPDATE SET destino.CODIGO = origen.NUEVO_CODIGO;

MERGE INTO HERRAMIENTA_EQUIPO destino
USING (
    SELECT ID_HERRAMIENTA_EQUIPO, 'HER-' || LPAD(TO_CHAR(ROW_NUMBER() OVER (ORDER BY ID_HERRAMIENTA_EQUIPO)), 6, '0') AS NUEVO_CODIGO
      FROM HERRAMIENTA_EQUIPO
) origen
ON (destino.ID_HERRAMIENTA_EQUIPO = origen.ID_HERRAMIENTA_EQUIPO)
WHEN MATCHED THEN UPDATE SET destino.CODIGO_HERRAMIENTA = origen.NUEVO_CODIGO;

