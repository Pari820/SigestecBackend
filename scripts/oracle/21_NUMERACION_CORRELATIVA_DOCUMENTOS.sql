DELETE FROM CORRELATIVO_DOCUMENTO;
INSERT INTO CORRELATIVO_DOCUMENTO (TIPO_DOCUMENTO, ANIO, ULTIMO_NUMERO)
SELECT t.TIPO_DOCUMENTO, y.ANIO, 0
  FROM (
      SELECT 'SOLICITUD' TIPO_DOCUMENTO FROM DUAL UNION ALL
      SELECT 'COTIZACION' FROM DUAL UNION ALL
      SELECT 'ORDEN_COMPRA' FROM DUAL UNION ALL
      SELECT 'ORDEN_TRABAJO' FROM DUAL UNION ALL
      SELECT 'ATS' FROM DUAL UNION ALL
      SELECT 'EJECUCION' FROM DUAL UNION ALL
      SELECT 'INFORME_TECNICO' FROM DUAL
  ) t
 CROSS JOIN (SELECT 2000 + LEVEL - 1 ANIO FROM DUAL CONNECT BY LEVEL <= 101) y;
INSERT INTO CORRELATIVO_DOCUMENTO (TIPO_DOCUMENTO, ANIO, ULTIMO_NUMERO) VALUES ('MATERIAL', 0, 0);
INSERT INTO CORRELATIVO_DOCUMENTO (TIPO_DOCUMENTO, ANIO, ULTIMO_NUMERO) VALUES ('HERRAMIENTA', 0, 0);

UPDATE CORRELATIVO_DOCUMENTO c SET ULTIMO_NUMERO =
    (SELECT COUNT(*) FROM SOLICITUD_SERVICIO x WHERE EXTRACT(YEAR FROM x.FECHA_SOLICITUD) = c.ANIO)
 WHERE TIPO_DOCUMENTO = 'SOLICITUD';
UPDATE CORRELATIVO_DOCUMENTO c SET ULTIMO_NUMERO =
    (SELECT COUNT(*) FROM COTIZACION x WHERE EXTRACT(YEAR FROM x.FECHA_EMISION) = c.ANIO)
 WHERE TIPO_DOCUMENTO = 'COTIZACION';
UPDATE CORRELATIVO_DOCUMENTO c SET ULTIMO_NUMERO =
    (SELECT COUNT(*) FROM ORDEN_COMPRA x WHERE EXTRACT(YEAR FROM x.FECHA_EMISION) = c.ANIO)
 WHERE TIPO_DOCUMENTO = 'ORDEN_COMPRA';
UPDATE CORRELATIVO_DOCUMENTO c SET ULTIMO_NUMERO =
    (SELECT COUNT(*) FROM ORDEN_TRABAJO ot JOIN ORDEN_COMPRA oc ON oc.ID_ORDEN_COMPRA = ot.ID_ORDEN_COMPRA
      WHERE EXTRACT(YEAR FROM NVL(oc.FECHA_EMISION, SYSDATE)) = c.ANIO)
 WHERE TIPO_DOCUMENTO = 'ORDEN_TRABAJO';
UPDATE CORRELATIVO_DOCUMENTO c SET ULTIMO_NUMERO =
    (SELECT COUNT(*) FROM ANALISIS_TRABAJO_SEGURO x WHERE EXTRACT(YEAR FROM x.FECHA_REGISTRO) = c.ANIO)
 WHERE TIPO_DOCUMENTO = 'ATS';
UPDATE CORRELATIVO_DOCUMENTO c SET ULTIMO_NUMERO =
    (SELECT COUNT(*) FROM EJECUCION_SERVICIO x WHERE EXTRACT(YEAR FROM x.FECHA_EJECUCION) = c.ANIO)
 WHERE TIPO_DOCUMENTO = 'EJECUCION';
UPDATE CORRELATIVO_DOCUMENTO c SET ULTIMO_NUMERO =
    (SELECT COUNT(*) FROM INFORME_TECNICO x WHERE EXTRACT(YEAR FROM x.FECHA_INFORME) = c.ANIO)
 WHERE TIPO_DOCUMENTO = 'INFORME_TECNICO';
UPDATE CORRELATIVO_DOCUMENTO SET ULTIMO_NUMERO = (SELECT COUNT(*) FROM MATERIAL)
 WHERE TIPO_DOCUMENTO = 'MATERIAL' AND ANIO = 0;
UPDATE CORRELATIVO_DOCUMENTO SET ULTIMO_NUMERO = (SELECT COUNT(*) FROM HERRAMIENTA_EQUIPO)
 WHERE TIPO_DOCUMENTO = 'HERRAMIENTA' AND ANIO = 0;

COMMIT;

