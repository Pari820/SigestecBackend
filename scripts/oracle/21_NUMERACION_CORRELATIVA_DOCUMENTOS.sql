DECLARE
    PROCEDURE agregar_unico_si_falta(p_tabla VARCHAR2, p_constraint VARCHAR2, p_columna VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS
         WHERE TABLE_NAME = UPPER(p_tabla) AND CONSTRAINT_NAME = UPPER(p_constraint);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || DBMS_ASSERT.SIMPLE_SQL_NAME(UPPER(p_tabla)) ||
                              ' ADD CONSTRAINT ' || DBMS_ASSERT.SIMPLE_SQL_NAME(UPPER(p_constraint)) ||
                              ' UNIQUE (' || DBMS_ASSERT.SIMPLE_SQL_NAME(UPPER(p_columna)) || ')';
        END IF;
    END;
BEGIN
    agregar_unico_si_falta('SOLICITUD_SERVICIO', 'UQ_SOLICITUD_CODIGO', 'CODIGO_SOLICITUD');
    agregar_unico_si_falta('ORDEN_COMPRA', 'UQ_ORDEN_COMPRA_CODIGO_INT', 'CODIGO_INTERNO');
    agregar_unico_si_falta('ANALISIS_TRABAJO_SEGURO', 'UQ_ATS_NUMERO', 'NUMERO_ATS');
    agregar_unico_si_falta('EJECUCION_SERVICIO', 'UQ_EJECUCION_NUMERO', 'NUMERO_EJECUCION');
END;
/

