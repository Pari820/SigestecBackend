ALTER TABLE USUARIO ADD (token_version NUMBER(19));

CREATE TABLE RECUPERACION_CLAVE (
    id_recuperacion NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario NUMBER(19) NOT NULL,
    token_hash VARCHAR2(64 CHAR) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_expiracion TIMESTAMP NOT NULL,
    fecha_uso TIMESTAMP,
    CONSTRAINT FK_RECUP_CLAVE_USUARIO FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario),
    CONSTRAINT UK_RECUP_CLAVE_HASH UNIQUE (token_hash)
);
CREATE INDEX IX_RECUP_CLAVE_USUARIO ON RECUPERACION_CLAVE(id_usuario);
