CREATE TABLE AUDITORIA_EVENTO (
    id_auditoria NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMP(6) NOT NULL,
    usuario VARCHAR2(60 CHAR) NOT NULL,
    accion VARCHAR2(50 CHAR) NOT NULL,
    entidad VARCHAR2(60 CHAR) NOT NULL,
    entidad_id NUMBER(19),
    detalle VARCHAR2(500 CHAR),
    request_id VARCHAR2(36 CHAR)
);
CREATE INDEX IX_AUDITORIA_FECHA ON AUDITORIA_EVENTO (fecha);
CREATE INDEX IX_AUDITORIA_USUARIO ON AUDITORIA_EVENTO (usuario, fecha);
CREATE INDEX IX_AUDITORIA_ACCION ON AUDITORIA_EVENTO (accion, fecha);
