-- SIGESTEC - Numeracion automatica de actas de conformidad
-- Ejecutar UNA SOLA VEZ como propietario del esquema SIGESTEC_ADS,
-- despues de 21_NUMERACION_CORRELATIVA_DOCUMENTOS.sql.
--
-- ADVERTENCIA: script destinado a datos de PRUEBA. Respaldar antes de ejecutar.
-- Renumera NUMERO_ACTA en orden por FECHA_CONFORMIDAD e ID interno.
-- NO modifica ID_CONFORMIDAD_SERVICIO ni relaciones con OT/informe/empleado.

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
      FROM USER_TABLES
     WHERE TABLE_NAME = 'CORRELATIVO_DOCUMENTO';
    IF v_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20021,
            'No existe CORRELATIVO_DOCUMENTO. Ejecuta primero el script 21_NUMERACION_CORRELATIVA_DOCUMENTOS.sql.');
    END IF;

    SELECT COUNT(*) INTO v_count
      FROM CORRELATIVO_DOCUMENTO
     WHERE TIPO_DOCUMENTO = 'ACTA_CONFORMIDAD' AND ANIO = 0;
    IF v_count = 0 THEN
        INSERT INTO CORRELATIVO_DOCUMENTO (TIPO_DOCUMENTO, ANIO, ULTIMO_NUMERO)
        VALUES ('ACTA_CONFORMIDAD', 0, 0);
    END IF;
END;
/

-- Evita colisiones temporales con la restriccion UNIQUE de NUMERO_ACTA.
UPDATE CONFORMIDAD_SERVICIO
   SET NUMERO_ACTA = 'TMP-ACTA-' || TO_CHAR(ID_CONFORMIDAD_SERVICIO);

-- Renumeracion de actas existentes por año, fecha de conformidad e ID interno.
MERGE INTO CONFORMIDAD_SERVICIO destino
USING (
    SELECT ID_CONFORMIDAD_SERVICIO,
           'ACTA-' || TO_CHAR(FECHA_CONFORMIDAD, 'YYYY') || '-' ||
           LPAD(TO_CHAR(ROW_NUMBER() OVER (
               PARTITION BY TO_CHAR(FECHA_CONFORMIDAD, 'YYYY')
               ORDER BY FECHA_CONFORMIDAD, ID_CONFORMIDAD_SERVICIO
           )), 3, '0') AS NUEVO_NUMERO
      FROM CONFORMIDAD_SERVICIO
) origen
ON (destino.ID_CONFORMIDAD_SERVICIO = origen.ID_CONFORMIDAD_SERVICIO)
WHEN MATCHED THEN UPDATE SET destino.NUMERO_ACTA = origen.NUEVO_NUMERO;

-- Sincroniza los contadores anuales con la cantidad de actas ya registradas.
MERGE INTO CORRELATIVO_DOCUMENTO destino
USING (
    SELECT EXTRACT(YEAR FROM FECHA_CONFORMIDAD) AS ANIO, COUNT(*) AS TOTAL
      FROM CONFORMIDAD_SERVICIO
     GROUP BY EXTRACT(YEAR FROM FECHA_CONFORMIDAD)
) origen
ON (destino.TIPO_DOCUMENTO = 'ACTA_CONFORMIDAD' AND destino.ANIO = origen.ANIO)
WHEN MATCHED THEN UPDATE SET destino.ULTIMO_NUMERO = origen.TOTAL
WHEN NOT MATCHED THEN
    INSERT (TIPO_DOCUMENTO, ANIO, ULTIMO_NUMERO)
    VALUES ('ACTA_CONFORMIDAD', origen.ANIO, origen.TOTAL);

COMMIT;

-- Verificacion: deben aparecer ACTA-AAAA-001, ACTA-AAAA-002, etc.
SELECT ID_CONFORMIDAD_SERVICIO, NUMERO_ACTA, FECHA_CONFORMIDAD
  FROM CONFORMIDAD_SERVICIO
 ORDER BY FECHA_CONFORMIDAD, ID_CONFORMIDAD_SERVICIO;

SELECT TIPO_DOCUMENTO, ANIO, ULTIMO_NUMERO
  FROM CORRELATIVO_DOCUMENTO
 WHERE TIPO_DOCUMENTO = 'ACTA_CONFORMIDAD'
 ORDER BY ANIO;
